// Package policy implements a deliberately closed purchase-policy compiler.
// It does not infer authorization from arbitrary SQL or arbitrary Go programs.
package policy

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"io"
	"os"
	"slices"
	"strings"
)

type Policy struct {
	Version         int      `json:"version"`
	Resource        string   `json:"resource"`
	TenantField     string   `json:"tenantField"`
	ReadRoles       []string `json:"readRoles"`
	CreateRoles     []string `json:"createRoles"`
	ApproveRoles    []string `json:"approveRoles"`
	ProtectedFields []string `json:"protectedFields"`
	Approval        struct {
		From         string `json:"from"`
		To           string `json:"to"`
		DisallowSelf bool   `json:"disallowSelf"`
	} `json:"approval"`
}

func Parse(b []byte) (Policy, error) {
	var p Policy
	d := json.NewDecoder(bytes.NewReader(b))
	d.DisallowUnknownFields()
	if err := d.Decode(&p); err != nil {
		return p, err
	}
	if err := d.Decode(new(any)); err != io.EOF {
		return p, fmt.Errorf("expected one JSON object")
	}
	if p.Version != 1 || p.Resource != "Purchase" || p.TenantField != "tenantId" {
		return p, fmt.Errorf("unsupported policy version, resource or tenant field")
	}
	if p.Approval.From != "submitted" || p.Approval.To != "approved" || !p.Approval.DisallowSelf {
		return p, fmt.Errorf("approval must enforce submitted -> approved and separation of duties")
	}
	fields := slices.Clone(p.ProtectedFields)
	slices.Sort(fields)
	if !slices.Equal(fields, []string{"createdBy", "internalNote", "tenantId"}) {
		return p, fmt.Errorf("protected field set must be complete")
	}
	for _, roles := range [][]string{p.ReadRoles, p.CreateRoles, p.ApproveRoles} {
		if len(roles) == 0 {
			return p, fmt.Errorf("roles cannot be empty")
		}
		seen := map[string]bool{}
		for _, r := range roles {
			if (r != "requester" && r != "approver") || seen[r] {
				return p, fmt.Errorf("unknown or duplicate role %q", r)
			}
			seen[r] = true
		}
	}
	return p, nil
}
func Load(path string) (Policy, error) {
	b, e := os.ReadFile(path)
	if e != nil {
		return Policy{}, e
	}
	return Parse(b)
}
func rolesSQL(roles []string) string {
	r := slices.Clone(roles)
	slices.Sort(r)
	for i := range r {
		r[i] = "'" + r[i] + "'"
	}
	return strings.Join(r, ",")
}
func Compile(p Policy) string {
	// All dynamic strings are validated closed enums. No general expression evaluator.
	return fmt.Sprintf(`-- Generated by appctl compile. Do not edit.
ALTER TABLE "Purchase" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "Purchase" FORCE ROW LEVEL SECURITY;
REVOKE ALL ON "Purchase" FROM app_runtime;
GRANT SELECT (id,"tenantId","createdBy",title,amount,status) ON "Purchase" TO app_runtime;
GRANT INSERT (id,"tenantId","createdBy",title,amount,status) ON "Purchase" TO app_runtime;
GRANT UPDATE (status) ON "Purchase" TO app_runtime;
CREATE POLICY purchase_read ON "Purchase" FOR SELECT TO app_runtime
 USING ("tenantId" = current_setting('app.tenant', true) AND current_setting('app.role', true) IN (%s));
CREATE POLICY purchase_create ON "Purchase" FOR INSERT TO app_runtime
 WITH CHECK ("tenantId" = current_setting('app.tenant', true) AND "createdBy" = current_setting('app.user', true)
 AND current_setting('app.role', true) IN (%s) AND status = 'submitted');
CREATE POLICY purchase_approve ON "Purchase" FOR UPDATE TO app_runtime
 USING ("tenantId" = current_setting('app.tenant', true) AND current_setting('app.role', true) IN (%s)
 AND "createdBy" <> current_setting('app.user', true) AND status = 'submitted')
 WITH CHECK ("tenantId" = current_setting('app.tenant', true) AND status = 'approved');
`, rolesSQL(p.ReadRoles), rolesSQL(p.CreateRoles), rolesSQL(p.ApproveRoles))
}
func Digest(b []byte) string { s := sha256.Sum256(b); return hex.EncodeToString(s[:]) }
